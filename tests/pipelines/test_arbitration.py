from data.pipelines.rfp_produce.arbitration import detect_conflicts, plan_resolutions
from data.pipelines.rfp_produce.fixtures import approve, seed_ticket


def _ids(store, tid):
    return [c["conflict_id"] for c in detect_conflicts(store.get_meta(tid), store.list_sections(tid))]


def test_clean_tickets_have_no_conflicts(env):
    store, _, _ = env
    seed_ticket(store, "T1", "meridian")
    seed_ticket(store, "T2", "thames")
    assert _ids(store, "T1") == [] and _ids(store, "T2") == []


def test_each_trigger_is_detected(env):
    store, _, _ = env
    seed_ticket(store, "P", "phi")
    seed_ticket(store, "C", "capacity")
    seed_ticket(store, "W", "wrong_clause")
    assert _ids(store, "P") == ["phi-detected"]
    assert _ids(store, "C") == ["capacity-vs-population"]
    assert _ids(store, "W") == ["baa-dpa-mismatch"]


def test_fixed_arbiters_and_phi_defers_capacity(env):
    store, _, _ = env
    seed_ticket(store, "X", "capacity")
    s = store.get_section("X", "clinical")
    s.contains_phi = True
    store.upsert_section(s)
    meta, secs = store.get_meta("X"), store.list_sections("X")
    plan = plan_resolutions(detect_conflicts(meta, secs), secs)
    by_id = {r["conflict_id"]: r for r in plan["resolutions"]}
    assert by_id["phi-detected"]["arbiter"] == "claire.whitfield"
    assert by_id["capacity-vs-population"]["arbiter"] == "tom.callahan"
    assert by_id["capacity-vs-population"]["deferred"] is True


def test_phi_hard_stop_redacts_blocks_and_recovers(env):
    store, build, _ = env
    seed_ticket(store, "P", "phi")
    wf = build()
    out = wf.start("P")  # gate catches PHI at the start
    assert out["closing_outcome"] == "arbitrated"
    assert any(r["conflict_id"] == "phi-detected" for r in out["resolutions"])
    # regenerated by the clean hook -> new pending approvals, nothing synthesized
    assert out["final_document"] is None
    assert not store.get_section("P", "clinical").phi_flagged
    for d in ("revenue", "clinical", "compliance"):
        out = wf.submit_decision("P", approve(d))
    assert out["status"] == "done"
    trace = [e.agent for e in wf.trace("P")]
    assert "arbitration:claire.whitfield" in trace


def test_phi_blocks_synthesis_without_hook(env):
    store, build, _ = env
    seed_ticket(store, "P", "phi")
    wf = build(hook=None)
    out = wf.start("P")
    assert out["departments"]["clinical"]["approval_status"] == "changes_requested"
    assert store.get_section("P", "clinical").draft_content.startswith("[REDACTED")
    assert out["status"] != "done" and out["final_document"] is None


def test_baa_dpa_mismatch_forces_compliance_revision(env):
    store, build, _ = env
    seed_ticket(store, "W", "wrong_clause")
    wf = build()
    out = wf.start("W")
    assert any(r["conflict_id"] == "baa-dpa-mismatch" for r in out["resolutions"])
    assert store.get_section("W", "compliance").effective_clauses() == ["DPA_UK_GDPR"]


def test_capacity_conflict_revises_both_and_completes(env):
    store, build, _ = env
    seed_ticket(store, "C", "capacity")
    wf = build()
    out = wf.start("C")
    assert any(r["arbiter"] == "tom.callahan" for r in out["resolutions"])
    assert store.get_section("C", "revenue").revision_count == 1
    assert store.get_section("C", "clinical").revision_count == 1
    for d in ("revenue", "clinical", "compliance"):
        out = wf.submit_decision("C", approve(d))
    assert out["status"] == "done"


def test_approved_section_reopened_when_late_conflict_appears(env):
    store, build, _ = env
    seed_ticket(store, "T1")
    wf = build()
    wf.start("T1")
    wf.submit_decision("T1", approve("compliance"))
    wf.submit_decision("T1", approve("revenue"))
    # a late edit by Part 2 introduces PHI on clinical
    s = store.get_section("T1", "clinical")
    s.contains_phi = True
    store.upsert_section(s)
    out = wf.submit_decision("T1", approve("clinical"))
    assert out["status"] != "done"
    assert out["departments"]["compliance"]["approval_status"] == "pending"  # reopened
